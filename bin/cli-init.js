/**
 * Create project from template
 */
async function createProject(options) {
  const projectPath = path.join(process.cwd(), options.name);
  
  console.log(`\n🚀 Creating ${options.template} project: ${options.name}\n`);
  
  // Check if directory exists
  if (await fs.pathExists(projectPath)) {
    throw new Error(`Directory ${options.name} already exists`);
  }
  
  // Create project directory
  await fs.ensureDir(projectPath);
  
  // Generate files
  console.log('📝 Generating configuration files...');
  
  // package.json
  const packageJson = generatePackageJson(options);
  await fs.writeJSON(path.join(projectPath, 'package.json'), packageJson, { spaces: 2 });
  
  // boilerplate.config.js
  const config = generateConfig(options);
  await fs.writeFile(path.join(projectPath, 'boilerplate.config.js'), config);
  
  // .env.example
  const envExample = generateEnvExample(options);
  await fs.writeFile(path.join(projectPath, '.env.example'), envExample);
  
  // .gitignore
  await fs.writeFile(path.join(projectPath, '.gitignore'), `node_modules/
dist/
.env
*.log
.DS_Store
`);
  
  // README.md
  const readme = generateReadme(options);
  await fs.writeFile(path.join(projectPath, 'README.md'), readme);
  
  // Generate service structure
  console.log('📦 Creating service structure...');
  await generateServiceStructure(projectPath, options);
  
  // Generate main file
  console.log('🔧 Generating application entry point...');
  await generateMainFile(projectPath, options);
  
  // Create additional directories
  await fs.ensureDir(path.join(projectPath, 'types'));
  
  if (options.features.testing) {
    await fs.ensureDir(path.join(projectPath, 'tests'));
  }
  
  console.log('\n✅ Project created successfully!\n');
  console.log('Next steps:\n');
  console.log(`  cd ${options.name}`);
  console.log('  npm install');
  console.log('  cp .env.example .env');
  console.log('  npm run dev\n');
}

/**
 * Interactive mode
 */
async function interactiveInit() {
  const answers = await inquirer.prompt([
    {
      type: 'input',
      name: 'name',
      message: 'Project name:',
      default: 'my-boilerplate-app',
      validate: (input) => {
        if (!/^[a-z0-9-]+$/.test(input)) {
          return 'Project name must contain only lowercase letters, numbers, and hyphens';
        }
        return true;
      }
    },
    {
      type: 'list',
      name: 'template',
      message: 'Select template:',
      choices: Object.entries(TEMPLATES).map(([key, value]) => ({
        name: `${value.name} - ${value.description}`,
        value: key
      }))
    },
    {
      type: 'checkbox',
      name: 'features',
      message: 'Select features:',
      choices: Object.entries(FEATURES).map(([key, value]) => ({
        name: value.name,
        value: key,
        checked: value.enabled
      }))
    },
    {
      type: 'input',
      name: 'description',
      message: 'Project description (optional):'
    }
  ]);
  
  // Convert features array to object
  const features = {};
  Object.keys(FEATURES).forEach(key => {
    features[key] = answers.features.includes(key);
  });
  
  return {
    ...answers,
    features
  };
}

/**
 * CLI Commands
 */
program
  .name('boilerplate')
  .description('Boilerplate CLI - Initialize and manage microservices projects')
  .version('1.0.0');

program
  .command('init')
  .description('Initialize a new boilerplate project')
  .option('-n, --name <name>', 'Project name')
  .option('-t, --template <template>', 'Template: monolith, microservices, serverless, minimal', 'monolith')
  .option('-i, --interactive', 'Interactive mode')
  .option('--typescript', 'Enable TypeScript')
  .option('--no-graphql', 'Disable GraphQL')
  .option('--no-database', 'Disable database')
  .option('--auth', 'Enable authentication')
  .option('--tracing', 'Enable distributed tracing')
  .option('--docker', 'Include Docker configuration')
  .action(async (options) => {
    try {
      let projectOptions;
      
      if (options.interactive) {
        projectOptions = await interactiveInit();
      } else {
        if (!options.name) {
          console.error('Error: Project name is required. Use --name or --interactive');
          process.exit(1);
        }
        
        projectOptions = {
          name: options.name,
          template: options.template,
          features: {
            typescript: options.typescript || false,
            graphql: options.graphql !== false,
            database: options.database !== false,
            authentication: options.auth || false,
            tracing: options.tracing || false,
            testing: true,
            docker: options.docker || false,
            kubernetes: false
          }
        };
      }
      
      await createProject(projectOptions);
    } catch (error) {
      console.error('Error:', error.message);
      process.exit(1);
    }
  });

program.parse();
