/**
 * Generate .env.example
 */
function generateEnvExample(options) {
  let content = `# Environment Variables for ${options.name}\n\n`;
  
  if (options.features.database) {
    content += `# Database\nDATABASE_URL=mongodb://localhost:27017\nDATABASE_NAME=${options.name}\n\n`;
  }
  
  content += `# Server\nPORT=4000\nHOST=0.0.0.0\nNODE_ENV=development\n\n`;
  
  if (options.features.authentication) {
    content += `# Authentication\nJWT_SECRET=your-secret-key-change-this\n\n`;
  }
  
  if (options.features.tracing) {
    content += `# Tracing\nTRACING_ENABLED=true\nJAEGER_ENDPOINT=http://localhost:14268/api/traces\n\n`;
  }
  
  content += `# Logging\nLOG_LEVEL=info\nLOG_FORMAT=json\n`;
  
  return content;
}

/**
 * Generate basic service structure
 */
async function generateServiceStructure(projectPath, options) {
  const servicesDir = path.join(projectPath, 'services');
  await fs.ensureDir(servicesDir);
  
  // Create example service
  const exampleServiceDir = path.join(servicesDir, 'ExampleService');
  await fs.ensureDir(exampleServiceDir);
  
  // Entity
  const entityDir = path.join(exampleServiceDir, 'entity');
  await fs.ensureDir(entityDir);
  await fs.writeFile(
    path.join(entityDir, 'Example.js'),
    `/**
 * Example Entity
 * @class Example
 */
export class Example {
  constructor(data) {
    this.id = data.id;
    this.name = data.name;
    this.createdAt = data.createdAt || new Date();
    this.updatedAt = data.updatedAt || new Date();
  }

  validate() {
    const errors = [];
    if (!this.name) errors.push('Name is required');
    return errors;
  }
}
`
  );
  
  // Service
  const serviceDir = path.join(exampleServiceDir, 'service');
  await fs.ensureDir(serviceDir);
  await fs.writeFile(
    path.join(serviceDir, 'ExampleService.js'),
    `import { Microservice } from '@dualitysol/boilerplate';
import { Example } from '../entity/Example.js';

/**
 * ExampleService - Business Logic Layer
 */
export class ExampleService extends Microservice {
  get collectionName() {
    return 'examples';
  }

  /**
   * Create a new example
   * @param {Object} input - Example data
   * @param {string} input.name - Example name
   * @returns {Promise<Example>}
   */
  async createExample(input) {
    const entity = new Example(input);
    
    const errors = entity.validate();
    if (errors.length > 0) {
      throw new Error(errors.join(', '));
    }
    
    const saved = await this.createOne(entity);
    return new Example(saved);
  }

  /**
   * Get example by ID
   * @param {string} id - Example ID
   * @returns {Promise<Example|null>}
   */
  async getExample(id) {
    const data = await this.findOne({ _id: id });
    return data ? new Example(data) : null;
  }
}
`
  );
  
  // GraphQL resolvers (if enabled)
  if (options.features.graphql) {
    const resolversDir = path.join(exampleServiceDir, 'resolvers');
    await fs.ensureDir(resolversDir);
    await fs.writeFile(
      path.join(resolversDir, 'index.js'),
      `/**
 * ExampleService GraphQL Resolvers
 */
export const resolvers = {
  Query: {
    example: async (_parent, { id }, { services }) => {
      return services.ExampleService.getExample(id);
    }
  },
  
  Mutation: {
    createExample: async (_parent, { input }, { services }) => {
      const example = await services.ExampleService.createExample(input);
      return {
        success: true,
        message: 'Example created successfully',
        data: example
      };
    }
  }
};
`
    );
    
    // GraphQL schema
    const typeDefsDir = path.join(exampleServiceDir, 'typeDefinitions');
    await fs.ensureDir(typeDefsDir);
    await fs.writeFile(
      path.join(typeDefsDir, 'index.gql'),
      `type Example {
  id: ID!
  name: String!
  createdAt: String!
  updatedAt: String!
}

type ExampleResponse {
  success: Boolean!
  message: String
  data: Example
}

type Query {
  example(id: ID!): Example
}

type Mutation {
  createExample(input: CreateExampleInput!): ExampleResponse!
}

input CreateExampleInput {
  name: String!
}
`
    );
  }
  
  // Index file
  await fs.writeFile(
    path.join(exampleServiceDir, 'index.js'),
    `export { ExampleService } from './service/ExampleService.js';
export { resolvers } from './resolvers/index.js';
export { default as typeDefs } from './typeDefinitions/index.gql';
`
  );
}

